"""Additional SLA, fairness, network-energy and carbon metrics.

These are model estimates. Calibrate coefficients before making real-cloud claims.
"""
from collections import defaultdict
from typing import Iterable, Mapping

def jains_fairness(values: Iterable[float]) -> float:
    xs = [max(0.0, float(x)) for x in values]
    if not xs or sum(x*x for x in xs) == 0:
        return 1.0 if not xs else 0.0
    return (sum(xs) ** 2) / (len(xs) * sum(x*x for x in xs))

def evaluate_completion_records(records, carbon_intensity_g_per_kwh=400.0,
                                network_j_per_mb=0.02):
    """records: iterable of dicts with arrival_time_s, completion_time_s,
    deadline_s, tenant_id, energy_joules_est, data_mb (optional).
    Returns extra metrics; records should be generated by a simulator.
    """
    rows = list(records)
    if not rows:
        return {}
    response = [max(0.0, float(r["completion_time_s"])-float(r["arrival_time_s"])) for r in rows]
    deadline_misses = sum(float(r["completion_time_s"]) > float(r["deadline_s"]) for r in rows)
    tenant_response = defaultdict(list)
    for r, rt in zip(rows, response):
        tenant_response[str(r.get("tenant_id", "tenant_1"))].append(rt)
    # Fairness is based on per-tenant mean response times transformed into service scores.
    # Higher scores mean lower average response time.
    tenant_scores = [1.0/(1.0 + sum(v)/len(v)) for v in tenant_response.values() if v]
    network_energy = sum(float(r.get("data_mb", 0.0)) for r in rows) * network_j_per_mb
    compute_energy = sum(float(r.get("energy_joules_est", 0.0)) for r in rows)
    total_energy = compute_energy + network_energy
    # 1 kWh = 3.6e6 joules; gCO2 = kWh * grid intensity.
    carbon_g = (total_energy / 3_600_000.0) * float(carbon_intensity_g_per_kwh)
    return {
        "task_count": len(rows),
        "mean_response_time_s": sum(response)/len(response),
        "deadline_violation_rate_pct": 100.0 * deadline_misses / len(rows),
        "tenant_jains_fairness": jains_fairness(tenant_scores),
        "network_energy_est_j": network_energy,
        "total_energy_est_j": total_energy,
        "carbon_est_gco2": carbon_g,
        "carbon_intensity_g_per_kwh": float(carbon_intensity_g_per_kwh),
    }
